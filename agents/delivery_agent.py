"""Delivery agent - builds a markdown digest and optionally emails it.

Always writes the digest to `output/digest_{date}.md` regardless of email
configuration, so demo runs produce a visible artefact even without SMTP.
"""

from __future__ import annotations

import asyncio
import logging
import smtplib
from collections import Counter
from datetime import datetime
from email.message import EmailMessage
from pathlib import Path
from typing import Any

from config import settings
from scoring.explainer import generate_motivation

log = logging.getLogger(__name__)


def _format_table(rows: list[list[str]]) -> str:
    """Render a GitHub-flavored markdown table."""
    if not rows:
        return ""
    header = rows[0]
    body = rows[1:]
    line = "| " + " | ".join(header) + " |"
    sep = "| " + " | ".join("---" for _ in header) + " |"
    body_lines = ["| " + " | ".join(r) + " |" for r in body]
    return "\n".join([line, sep, *body_lines])


def _aggregate_skill_gaps(jobs: list[dict[str, Any]]) -> list[tuple[str, int]]:
    """Count skill_gap occurrences across all analyzed jobs."""
    counter: Counter[str] = Counter()
    for j in jobs:
        for skill in j.get("skill_gaps") or []:
            skill = (skill or "").strip()
            if skill:
                counter[skill] += 1
    return counter.most_common(15)


async def build_digest(
    scraped_count: int,
    scored_count: int,
    analyzed_jobs: list[dict[str, Any]],
    run_id: str,
) -> tuple[str, str]:
    """Build (subject, markdown_body). Falls back gracefully without LLM."""
    date_str = datetime.utcnow().strftime("%Y-%m-%d")
    # Sort by the deterministic score (claude_score mirrors score_final*10,
    # see agents/orchestrator.py::_derive_legacy_fields), then raw similarity.
    ranked = sorted(
        analyzed_jobs,
        key=lambda j: (j.get("claude_score") or 0, j.get("raw_score") or 0),
        reverse=True,
    )
    top5 = ranked[:5]
    subject = f"JobRadar Daily Digest — {date_str} — {len(ranked)} matches"

    motivation = await generate_motivation(top5, pipeline_run_id=run_id)
    gaps = _aggregate_skill_gaps(ranked)

    table_rows: list[list[str]] = [["Title", "Company", "Score", "Apply?"]]
    for j in top5:
        score = j.get("claude_score")
        score_str = f"{score}/10" if score else "—"
        apply_flag = "YES" if j.get("apply_recommendation") else "hold"
        title = (j.get("title") or "").replace("|", "\\|")[:70]
        company = (j.get("company") or "").replace("|", "\\|")[:40]
        table_rows.append([title, company, score_str, apply_flag])

    gap_lines = (
        "\n".join(f"- **{skill}** — mentioned in {n} jobs" for skill, n in gaps)
        if gaps
        else "_No skill gaps flagged in this run._"
    )

    body = f"""# JobRadar Daily Digest — {date_str}

> {motivation}

## Summary

- **Run ID:** `{run_id}`
- **Scraped:** {scraped_count} jobs
- **Scored (deterministic):** {scored_count} jobs
- **Explained (LLM, top N only):** {sum(1 for j in analyzed_jobs if j.get("explanation"))} jobs
- **Top 5 recommended below**

## Top 5 Matches

{_format_table(table_rows)}

### Detailed reasoning

{_render_details(top5)}

## Skill gaps this week

{gap_lines}

---
_Generated by JobRadar — `{datetime.utcnow().isoformat()}Z`_
"""
    return subject, body


def _render_details(jobs: list[dict[str, Any]]) -> str:
    sections: list[str] = []
    for idx, j in enumerate(jobs, 1):
        score = j.get("claude_score") or 0
        reasoning = j.get("claude_reasoning") or "_(no reasoning)_"
        url = j.get("url") or ""
        highlights = j.get("highlights") or []
        gaps = j.get("skill_gaps") or []
        sections.append(
            f"**{idx}. {j.get('title','')} — {j.get('company','')}** (score: {score}/10)\n\n"
            f"{reasoning}\n\n"
            f"- Highlights: {', '.join(highlights) if highlights else '—'}\n"
            f"- Gaps: {', '.join(gaps) if gaps else '—'}\n"
            f"- Link: {url or '—'}\n"
        )
    return "\n".join(sections) if sections else "_No jobs to show._"


async def _send_email(subject: str, body: str) -> bool:
    """Send via SMTP. Returns True on success. Never raises."""
    if not settings.email_recipient:
        log.info("EMAIL_RECIPIENT not set - skipping SMTP delivery")
        return False
    if not (settings.email_sender and settings.email_password):
        log.warning("EMAIL_SENDER or EMAIL_PASSWORD not set - skipping SMTP delivery")
        return False

    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = settings.email_sender
    msg["To"] = settings.email_recipient
    msg.set_content(body)

    def _send() -> None:
        with smtplib.SMTP(settings.smtp_host, settings.smtp_port, timeout=20) as s:
            s.starttls()
            s.login(settings.email_sender, settings.email_password)
            s.send_message(msg)

    try:
        await asyncio.to_thread(_send)
        log.info("Sent digest to %s", settings.email_recipient)
        return True
    except Exception as e:
        log.error("SMTP send failed: %s", e)
        return False


def _write_markdown(body: str) -> Path:
    out_dir = Path(settings.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    date_str = datetime.utcnow().strftime("%Y-%m-%d")
    path = out_dir / f"digest_{date_str}.md"
    path.write_text(body, encoding="utf-8")
    return path


async def deliver(
    scraped_count: int,
    scored_count: int,
    analyzed_jobs: list[dict[str, Any]],
    run_id: str,
) -> dict[str, Any]:
    """Build digest, write markdown, optionally email. Returns metadata."""
    subject, body = await build_digest(scraped_count, scored_count, analyzed_jobs, run_id)
    path = await asyncio.to_thread(_write_markdown, body)
    emailed = await _send_email(subject, body)
    log.info("Digest written to %s (emailed=%s)", path, emailed)
    return {"path": str(path), "emailed": emailed, "subject": subject}
